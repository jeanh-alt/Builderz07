// Add coordinates to networks that don't have them
// This ensures all networks can be displayed on the map
export const networksWithCoords = sampleNetworks.map(network => ({
  ...network,
  lat: network.lat ?? getNetworkCoords(network)[0],
  lng: network.lng ?? getNetworkCoords(network)[1],
}));

// Get networks by region
export const getNetworksByRegion = (region: string): Network[] => {
  return networksWithCoords.filter(n => n.region === region);
};

// Get all unique regions from sample networks
export const getUniqueRegions = (): string[] => {
  return [...new Set(networksWithCoords.map(n => n.region))];
};
